@pytest.mark.asyncio
async def test_git_operations_safety_rules():
    """Verify GitOperations enforces strict safety rules: no force push, no direct push to main."""
    # 1. Force push prohibited
    with pytest.raises(PermissionError, match="Force push is strictly prohibited"):
        GitOperations.git_push(branch="feature/test", force=True)

    # 2. Direct push to main prohibited
    with pytest.raises(PermissionError, match="Direct push to protected branch 'main' is prohibited"):
        GitOperations.git_push(branch="main", force=False)

    # 3. Push requires explicit approval
    res = GitOperations.git_push(branch="feature/my-branch", approved=False)
    assert res["requires_approval"] is True
    assert res["status"] == "pending_approval"


