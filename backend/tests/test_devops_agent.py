@pytest.mark.asyncio
async def test_api_devops_deploy_requires_superuser(
    client: AsyncClient, auth_headers: dict, super_auth_headers: dict
):
    """POST /api/v1/devops/deploy rejects non-superusers with 403 and accepts superusers."""
    payload = {"environment": "staging", "version": "v1.1.0", "notes": "Test deploy"}

    # Non-superuser -> 403 Forbidden
    resp_forbidden = await client.post("/api/v1/devops/deploy", json=payload, headers=auth_headers)
    assert resp_forbidden.status_code == 403

    # Superuser -> 202 Accepted
    resp_ok = await client.post("/api/v1/devops/deploy", json=payload, headers=super_auth_headers)
    assert resp_ok.status_code == 202
    data = resp_ok.json()
    assert data["version"] == "v1.1.0"
    assert data["environment"] == "staging"
    assert data["status"] == "success"


@pytest.mark.asyncio
async def test_api_devops_deployments_list_and_rollback(
    client: AsyncClient, super_auth_headers: dict
):
    """Verify deployment listing and superuser rollback mechanism."""
    # 1. Trigger deployment
    dep_payload = {"environment": "production", "version": "v1.2.0-prod", "notes": "Initial release"}
    resp_deploy = await client.post("/api/v1/devops/deploy", json=dep_payload, headers=super_auth_headers)
    assert resp_deploy.status_code == 202
    created_id = resp_deploy.json()["id"]

    # 2. List deployments
    resp_list = await client.get("/api/v1/devops/deployments", headers=super_auth_headers)
    assert resp_list.status_code == 200
    deployments = resp_list.json()
    assert len(deployments) >= 1
    assert any(d["id"] == created_id for d in deployments)

    # 3. Rollback deployment
    resp_rb = await client.post(f"/api/v1/devops/rollback/{created_id}", headers=super_auth_headers)
    assert resp_rb.status_code == 200
    rb_data = resp_rb.json()
    assert rb_data["status"] == "rolled_back"
    assert rb_data["rollback_of"] == created_id
    assert "rollback-v1.2.0-prod" in rb_data["version"]
