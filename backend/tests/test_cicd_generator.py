"""Unit tests for GitHub Actions CI/CD Pipeline Generator (Phase 11.1)."""

import pytest
import yaml

from backend.app.tools.cicd_generator import CICDGenerator, GeneratedWorkflow


def test_ci_workflow_generation_and_valid_yaml():
    """Verify CI workflow generation and structural YAML syntax validity."""
    wf = CICDGenerator.generate_workflow("ci", project_name="rayhan-workbench")
    assert isinstance(wf, GeneratedWorkflow)
    assert wf.filename == "ci.yml"
    assert wf.workflow_type == "ci"
    assert wf.is_valid_yaml is True
    assert wf.job_count >= 4  # lint, test, security, build

    # Verify YAML structure
    parsed = yaml.safe_load(wf.yaml_content)
    assert "name" in parsed
    assert "on" in parsed or True in parsed
    assert "jobs" in parsed
    assert "lint" in parsed["jobs"]
    assert "test" in parsed["jobs"]
    assert "security" in parsed["jobs"]
    assert "build" in parsed["jobs"]


def test_cd_workflow_has_manual_approval_gate():
    """Verify CD workflow generation has manual approval gate and staging/production targets."""
    wf = CICDGenerator.generate_workflow("cd", project_name="rayhan-workbench")
    assert wf.filename == "cd.yml"
    assert wf.is_valid_yaml is True
    assert wf.has_approval_gate is True

    parsed = yaml.safe_load(wf.yaml_content)
    assert "deploy-staging" in parsed["jobs"]
    assert "deploy-production" in parsed["jobs"]
    # Production must depend on staging
    assert parsed["jobs"]["deploy-production"]["needs"] == "deploy-staging"


def test_pr_check_workflow_includes_core_checks():
    """Verify PR validation workflow contains typecheck, linting, and pytest suite."""
    wf = CICDGenerator.generate_workflow("pr", project_name="rayhan-workbench")
    assert wf.filename == "pr-check.yml"
    assert wf.is_valid_yaml is True
    assert "pull_request" in str(wf.triggers) or "pull_request" in wf.yaml_content

    parsed = yaml.safe_load(wf.yaml_content)
    assert "pr-checks" in parsed["jobs"]


def test_security_workflow_scheduled():
    """Verify Security audit workflow has scheduled cron configuration."""
    wf = CICDGenerator.generate_workflow("security", project_name="rayhan-workbench")
    assert wf.filename == "security.yml"
    assert wf.is_valid_yaml is True

    parsed = yaml.safe_load(wf.yaml_content)
    assert "jobs" in parsed
    assert "secret-scan" in parsed["jobs"]


def test_workflow_has_attribution_marker():
    """Ensure generated workflow includes non-destructive generated marker."""
    for wf_type in ["ci", "cd", "pr", "security"]:
        wf = CICDGenerator.generate_workflow(wf_type)
        assert "# Generated by DevOps Agent" in wf.yaml_content


def test_generate_all_workflows():
    """Verify batch generation of all workflows."""
    all_wfs = CICDGenerator.generate_all(project_name="rayhan-workbench")
    assert len(all_wfs) == 4
    for key in ["ci", "cd", "pr", "security"]:
        assert key in all_wfs
        assert all_wfs[key].is_valid_yaml is True


def test_invalid_workflow_type_raises():
    """Ensure invalid workflow type raises ValueError."""
    with pytest.raises(ValueError):
        CICDGenerator.generate_workflow("invalid_pipeline_type")
