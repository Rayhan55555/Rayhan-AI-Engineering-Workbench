import uuid
import pytest
from backend.app.agents.implementations.documentation_agent import DocumentationAgent
from backend.app.agents.base_agent import AgentTask, ExecutionContext, TaskScope
from backend.app.tools.doc_generator import DocGenerator

DUMMY_USER_ID = uuid.uuid4()


@pytest.mark.asyncio
async def test_documentation_agent_generate_api_docs():
    """Verify Documentation Agent generates complete markdown API reference."""
    agent = DocumentationAgent()
    task = AgentTask(
        agent_slug=agent.slug,
        instruction="generate API docs for all endpoints",
        scope=TaskScope.suggest,
        requested_by=DUMMY_USER_ID,
    )
    context = ExecutionContext(allowed_tools=agent.allowed_tools, dry_run=False)

    result = await agent.execute(task, context)
    assert result.success is True
    assert result.simulated is False
    assert "REST API Reference Manual" in result.output
    assert "Generated by Documentation Agent" in result.output
    assert any(a.name == "API_REFERENCE.md" for a in result.artifacts)


