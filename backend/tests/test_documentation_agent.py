@pytest.mark.asyncio
async def test_documentation_agent_write_requires_implement_scope():
    """Verify writing docs to disk without IMPLEMENT scope is rejected."""
    agent = DocumentationAgent()
    task = AgentTask(
        agent_slug=agent.slug,
        instruction="write API docs to docs/API_REFERENCE.md",
        scope=TaskScope.suggest,  # Not implement scope
        requested_by=DUMMY_USER_ID,
    )
    context = ExecutionContext(allowed_tools=agent.allowed_tools, dry_run=False)

    result = await agent.execute(task, context)
    assert result.success is False
    assert "requires IMPLEMENT scope" in result.output


def test_doc_generator_audit_metrics():
    """Verify DocGenerator.audit_documentation returns valid numbers and recommendations."""
    report = DocGenerator.audit_documentation()
    assert report.total_endpoints > 0
    assert report.coverage_percentage >= 0.0
    assert report.coverage_percentage <= 100.0
    assert isinstance(report.missing_docs, list)
    assert isinstance(report.recommendations, list)
