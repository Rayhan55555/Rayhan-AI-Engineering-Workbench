from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, Any, List, Optional
from pydantic import BaseModel, Field
from backend.app.architecture.templates import README_TEMPLATE, SETUP_GUIDE_TEMPLATE
from backend.app.tools.architecture_analyzer import ArchitectureAnalyzer


class GeneratedDoc(BaseModel):
    doc_type: str
    title: str
    content: str
    file_target: str
    word_count: int
    generated_at: str
    review_required: bool = True


class DocAuditReport(BaseModel):
    total_endpoints: int
    documented_endpoints: int
    undocumented_endpoints: int
    coverage_percentage: float
    missing_docs: List[Dict[str, str]] = Field(default_factory=list)
    quality_score: int  # 0 to 100
    recommendations: List[str] = Field(default_factory=list)


class DocGenerator:
    """
    Automated documentation generator and documentation auditor.
    Generates API references, READMEs, setup guides, architecture documents, and changelogs.
    """
    WORKSPACE_ROOT = Path("/app/applet").resolve()
    DOCS_DIR = WORKSPACE_ROOT / "docs"

    @classmethod
    def generate_api_docs(cls) -> GeneratedDoc:
        """Generates comprehensive markdown API reference for all FastAPI routers."""
        _, _, endpoints = ArchitectureAnalyzer.analyze_api_contracts()

        md_lines = [
            "# REST API Reference Manual",
            "",
            "<!-- Generated by Documentation Agent -->",
            "<!-- Review required before publishing -->",
            "",
            "All endpoints are prefixed with `/api/v1` and accept standard JSON payloads.",
            "Authentication: Bearer JWT Token in `Authorization` header.",
            "",
            "| Method | Endpoint | Router | Status | Description |",
            "| :--- | :--- | :--- | :--- | :--- |",
        ]

        for ep in endpoints:
            desc = ep["docstring"] if ep["is_documented"] else "⚠️ *Docstring missing*"
            md_lines.append(f"| `{ep['method']}` | `{ep['path']}` | `{ep['router']}` | {'✅ Documented' if ep['is_documented'] else '❌ Missing'} | {desc} |")

        content = "\n".join(md_lines)
        return GeneratedDoc(
            doc_type="api_reference",
            title="REST API Reference Manual",
            content=content,
            file_target="docs/API_REFERENCE.md",
            word_count=len(content.split()),
            generated_at=datetime.now(timezone.utc).isoformat(),
        )

    @classmethod
    def generate_readme(cls, project_name: str = "Rayhan AI Engineering Workbench") -> GeneratedDoc:
        """Generates complete, publication-grade README.md."""
        desc = "Personal AI engineering workspace and technical portfolio for Applied AI Systems Architect."
        content = README_TEMPLATE.format(
            project_name=project_name,
            description=desc,
        )

        return GeneratedDoc(
            doc_type="readme",
            title=f"README — {project_name}",
            content=content,
            file_target="README.md",
            word_count=len(content.split()),
            generated_at=datetime.now(timezone.utc).isoformat(),
        )

    @classmethod
    def generate_setup_guide(cls, project_name: str = "Rayhan AI Engineering Workbench") -> GeneratedDoc:
        """Generates step-by-step SETUP.md guide."""
        content = SETUP_GUIDE_TEMPLATE.format(
            project_name=project_name,
            repo_url="https://github.com/rayhan-ai/engineering-workbench.git",
            project_dir="engineering-workbench",
        )

        return GeneratedDoc(
            doc_type="setup_guide",
            title="Setup & Deployment Guide",
            content=content,
            file_target="docs/SETUP.md",
            word_count=len(content.split()),
            generated_at=datetime.now(timezone.utc).isoformat(),
        )

    @classmethod
    def generate_changelog(cls) -> GeneratedDoc:
        """Generates CHANGELOG.md adhering to Keep a Changelog standard."""
        today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
        lines = [
            "# Changelog",
            "",
            "All notable changes to the Rayhan AI Engineering Workbench are documented in this file.",
            "The format is based on [Keep a Changelog](https://keepachangelog.com/en/1.0.0/).",
            "",
            "<!-- Generated by Documentation Agent -->",
            "<!-- Review required before publishing -->",
            "",
            f"## [Phase 09] — {today}",
            "### Added",
            "- Architecture Agent: system topology analysis, AST layer verification, and circular dependency checks.",
            "- Documentation Agent: living API documentation synthesis, README generator, and coverage audits.",
            "- Diagram Generator: Mermaid.js flowcharts, ER diagrams, sequence flows, and state diagrams.",
            "- Architecture Decision Records: standardized ADR template generator and docs/adr/ scanner.",
            "",
            "## [Phase 08] — 2026-11-08",
            "### Added",
            "- Model Context Protocol (MCP 1.0): 18 standardized tools across GitHub, Filesystem, Web, DB, and Shell.",
            "- Human-in-the-Loop Approval Workflow with 10-minute expiry for all mutating operations.",
            "- Append-only Immutable Audit Trail with automatic credential masking.",
            "- Server-Sent Events (SSE) live streaming and WebSocket notification hub.",
            "",
            "## [Phase 07] — 2026-11-08",
            "### Added",
            "- AI Gateway abstraction layer with primary Gemini 1.5 and fallback Claude 3.5 routing.",
            "- Sliding window rate limiter and token/cost accounting in PostgreSQL.",
            "- Jinja2 prompt template inheritance system.",
            "",
            "## [Phases 01-06] — Foundation",
            "### Added",
            "- Dual-surface Next-style React SPA, FastAPI REST API, and PostgreSQL SQLAlchemy 2.x async session.",
            "- Agent lifecycle state machine with 4-tier permission model.",
            "- Coding Agent with sandbox file reader, diff generator, and scoped test runner.",
            "- Security Agent with 18+ AST rules, secret detector, and auth auditor.",
            "- Testing Agent with coverage analyzer, AST gap detector, and failure analyzer.",
        ]

        content = "\n".join(lines)
        return GeneratedDoc(
            doc_type="changelog",
            title="System Changelog",
            content=content,
            file_target="CHANGELOG.md",
            word_count=len(content.split()),
            generated_at=datetime.now(timezone.utc).isoformat(),
        )

    @classmethod
    def audit_documentation(cls) -> DocAuditReport:
        """Audits documentation completeness across API endpoints."""
        total, undoc, endpoints = ArchitectureAnalyzer.analyze_api_contracts()
        doc_count = max(0, total - undoc)
        coverage_pct = round((doc_count / total * 100), 1) if total > 0 else 100.0

        missing = [
            {"path": ep["path"], "method": ep["method"], "router": ep["router"]}
            for ep in endpoints
            if not ep["is_documented"]
        ]

        # Calculate quality score
        quality = int(coverage_pct * 0.9)  # Base on coverage
        if cls.DOCS_DIR.exists() and len(list(cls.DOCS_DIR.glob("*.md"))) > 0:
            quality += 10
        quality = min(100, quality)

        recs = []
        if undoc > 0:
            recs.append(f"Backfill docstrings for {undoc} endpoints lacking clear OpenAPI descriptions.")
        if coverage_pct < 90.0:
            recs.append("Run 'Documentation Agent: generate API docs' to update docs/API_REFERENCE.md.")
        if not (cls.WORKSPACE_ROOT / "README.md").exists():
            recs.append("Generate root README.md using the Documentation Agent.")

        return DocAuditReport(
            total_endpoints=total,
            documented_endpoints=doc_count,
            undocumented_endpoints=undoc,
            coverage_percentage=coverage_pct,
            missing_docs=missing[:30],
            quality_score=quality,
            recommendations=recs,
        )

    @classmethod
    def generate(cls, doc_type: str, target: Optional[str] = None) -> GeneratedDoc:
        dt = doc_type.lower()
        if dt in ("api", "api_docs", "reference"):
            return cls.generate_api_docs()
        elif dt in ("readme", "project_readme"):
            return cls.generate_readme()
        elif dt in ("setup", "setup_guide", "install"):
            return cls.generate_setup_guide()
        elif dt in ("changelog", "history"):
            return cls.generate_changelog()
        else:
            raise ValueError(f"Unknown doc_type: '{doc_type}'. Supported: api, readme, setup, changelog.")
