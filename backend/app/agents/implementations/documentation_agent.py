import json
from pathlib import Path
from typing import Dict, Any, List, Optional
from backend.app.agents.base_agent import (
    BaseAgent,
    AgentTask,
    AgentResult,
    ExecutionContext,
    ValidationResult,
    CapabilityDescription,
    Artifact,
    Evidence,
    TaskScope,
)
from backend.app.tools.doc_generator import DocGenerator, GeneratedDoc
from backend.app.gateway import ModelRouter, Message
from backend.app.config import settings


class DocumentationAgent(BaseAgent):
    """
    Documentation Agent — Phase 09 full functional implementation.
    Generates living OpenAPI reference docs, comprehensive READMEs, setup guides,
    changelogs, and audits documentation coverage across endpoints.
    """
    slug = "documentation-agent"
    name = "Documentation Agent"
    purpose = "Automatic OpenAPI documentation enrichment, README distillation, setup guide generation, and documentation coverage audits."
    phase = 9
    version = "1.0.0"
    allowed_tools = [
        "doc_generator",
        "file_reader",
        "code_analyzer",
    ]
    required_permissions = ["READ_ONLY", "SUGGEST", "IMPLEMENT"]
    limitations = [
        "All generated documents include 'Generated by Documentation Agent - Review Required' header",
        "Writing or updating files in /docs/ or README.md (IMPLEMENT scope) requires explicit human authorization",
        "Automated GitHub PR creation and push is locked until Phase 11",
        "Documentation coverage audit is scoped to FastAPI endpoints and markdown documents",
    ]

    WORKSPACE_ROOT = Path("/app/applet").resolve()

    async def validate_input(self, task: AgentTask) -> ValidationResult:
        if not task.instruction or len(task.instruction.strip()) < 3:
            return ValidationResult(valid=False, error="Instruction is too short (min 3 characters).")
        if len(task.instruction) > 2000:
            return ValidationResult(valid=False, error="Instruction exceeds maximum length of 2000 characters.")
        return ValidationResult(valid=True)

    async def execute(self, task: AgentTask, context: ExecutionContext) -> AgentResult:
        val = await self.validate_input(task)
        if not val.valid:
            return AgentResult(
                success=False,
                output=f"Input validation rejected: {val.error}",
                limitations=self.limitations,
                simulated=False,
            )

        instruction_lower = task.instruction.lower()
        artifacts: List[Artifact] = []
        evidence: List[Evidence] = []

        # 1. AUDIT & COVERAGE (READ_ONLY)
        if any(w in instruction_lower for w in ("audit", "coverage", "check docs", "missing")):
            audit_report = DocGenerator.audit_documentation()

            evidence.append(Evidence(
                source="doc_generator",
                snippet=f"Documented {audit_report.documented_endpoints}/{audit_report.total_endpoints} endpoints ({audit_report.coverage_percentage}% coverage). Quality score: {audit_report.quality_score}/100.",
                confidence=1.0,
            ))

            artifacts.append(Artifact(
                name="doc_coverage_report.json",
                artifact_type="json_report",
                content=audit_report.model_dump_json(indent=2),
                metadata={"coverage": audit_report.coverage_percentage, "quality": audit_report.quality_score},
            ))

            return AgentResult(
                success=True,
                output=audit_report.model_dump_json(indent=2),
                artifacts=artifacts,
                evidence=evidence,
                limitations=self.limitations,
                simulated=False,
            )

        # 2. DOCUMENT GENERATION (SUGGEST / IMPLEMENT)
        doc_type = "api"
        if "readme" in instruction_lower:
            doc_type = "readme"
        elif "setup" in instruction_lower or "install" in instruction_lower:
            doc_type = "setup"
        elif "changelog" in instruction_lower:
            doc_type = "changelog"

        is_write_task = any(w in instruction_lower for w in ("write", "save", "persist", "commit", "apply"))
        if is_write_task and task.scope != TaskScope.implement:
            return AgentResult(
                success=False,
                output="Writing documentation files to disk requires IMPLEMENT scope and explicit human approval.",
                limitations=self.limitations,
                simulated=False,
            )

        generated: GeneratedDoc = DocGenerator.generate(doc_type)

        # AI Gateway enhancement if keys configured
        if settings.GEMINI_API_KEY and settings.GEMINI_API_KEY != "your-gemini-api-key-here":
            try:
                router = ModelRouter()
                gw_res = await router.route_and_execute(
                    messages=[
                        Message(role="system", content="You are a Technical Writer. Polish and enhance this markdown documentation. Ensure pristine formatting."),
                        Message(role="user", content=generated.content),
                    ],
                    task_type="simple",
                )
                if gw_res and gw_res.content:
                    generated.content = gw_res.content
                    generated.word_count = len(gw_res.content.split())
            except Exception:
                pass

        # Write to disk if IMPLEMENT scope authorized
        written = False
        target_path_str = generated.file_target
        if is_write_task and not context.dry_run:
            full_path = self.WORKSPACE_ROOT / generated.file_target
            full_path.parent.mkdir(parents=True, exist_ok=True)
            with open(full_path, "w", encoding="utf-8") as f:
                f.write(generated.content)
            written = True

        evidence.append(Evidence(
            source="doc_generator",
            snippet=f"Generated {generated.title} ({generated.word_count} words). Written to disk: {written}.",
            confidence=1.0,
        ))

        artifacts.append(Artifact(
            name=Path(generated.file_target).name,
            artifact_type="markdown_document",
            content=generated.content,
            metadata={"file_target": generated.file_target, "written": written},
        ))

        return AgentResult(
            success=True,
            output=generated.content,
            artifacts=artifacts,
            evidence=evidence,
            limitations=self.limitations,
            simulated=False,
        )

    async def describe_capabilities(self) -> CapabilityDescription:
        return CapabilityDescription(
            slug=self.slug,
            name=self.name,
            purpose=self.purpose,
            phase=self.phase,
            version=self.version,
            allowed_tools=self.allowed_tools,
            required_permissions=self.required_permissions,
            limitations=self.limitations,
        )
